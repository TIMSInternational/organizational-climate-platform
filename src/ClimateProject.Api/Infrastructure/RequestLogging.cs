using System.Diagnostics;

namespace ClimateProject.Api.Infrastructure;

/// <summary>
/// One log line per request, and a request id the caller can quote back (#158).
///
/// <para>
/// <b>Why.</b> Measured 2026-11-15: a refused request -- a 400, a 403, a 404 -- left no trace in
/// CloudWatch at all. The categories that reached the application log group were EF commands,
/// the workers and their heartbeats; <c>Microsoft.AspNetCore</c> is set to Warning in
/// <c>appsettings.json</c>, so the framework's own "Request finished" line never ships. A
/// client reporting "it said error" could not be matched to anything.
/// </para>
/// <para>
/// <b>What the line carries, and what it must never carry.</b> The method, the ROUTE TEMPLATE
/// (<c>/surveys/{id:guid}/results</c>, placeholders unexpanded), the status code, the elapsed
/// milliseconds and <see cref="HttpContext.TraceIdentifier"/>. Never <c>Request.Path</c> and
/// never the query string: several paths in this API carry a bearer credential
/// (<c>/survey-invitations/{token}</c>, <c>/invitations/{token}/accept</c>), every id in a path
/// names a person or a survey, and <c>Request.Path</c> is percent-DECODED, so logging it would
/// let any caller write a newline into the stream the alarms read. The template comes from the
/// endpoint table through <see cref="RateLimitPolicies.RouteNameFor"/> -- the same function the
/// rate limiter's rejection line already uses for the same reason -- so nothing in the line is
/// free text from the wire.
/// </para>
/// <para>
/// <b>The probes are skipped.</b> App Runner polls <c>/ready</c> every few seconds on every
/// instance, the synthetic probe polls <c>/health</c> and <c>/version</c>; a line for each would
/// be most of the log group and all of its cost. They still get the <c>X-Request-Id</c> header.
/// </para>
/// <para>
/// <b>The id.</b> <see cref="HttpContext.TraceIdentifier"/> is generated by the server for every
/// request; nothing a caller sends can set it, which is why an incoming <c>X-Request-Id</c> is
/// deliberately NOT honoured -- it would be a caller-chosen string written into every line. It
/// is returned in <see cref="HeaderName"/> on every response and as <c>requestId</c> in the JSON
/// body of every centrally produced error (the exception handler in <c>Program.cs</c>, the 413 in
/// <see cref="SecurityHardening"/>), and CORS exposes the header to the web
/// (<c>WithExposedHeaders</c> in <c>Program.cs</c>).
/// </para>
/// </summary>
public static class RequestLogging
{
    /// <summary>The response header carrying <see cref="HttpContext.TraceIdentifier"/>.</summary>
    public const string HeaderName = "X-Request-Id";

    /// <summary>The logger category of the request line.</summary>
    public const string LogCategory = "ClimateProject.Api.Requests";

    /// <summary>
    /// The literal every request line starts with, so a CloudWatch filter
    /// (<c>--filter-pattern '"api-request"'</c>) finds exactly these lines. Chosen not to
    /// collide with ASP.NET Core's own "Request finished" text, nor with any route.
    /// </summary>
    public const string LinePrefix = "api-request";

    /// <summary>
    /// Paths that produce no request line: exactly the probe paths. Matched against the raw
    /// path, case-insensitively, so a probe never costs a line however it is cased.
    /// </summary>
    public static readonly IReadOnlySet<string> UnloggedPaths =
        new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "/health", "/ready", "/version" };

    internal static bool IsUnloggedPath(PathString path)
        => path.HasValue && UnloggedPaths.Contains(path.Value!);

    /// <summary>
    /// The middleware. Registered FIRST in the pipeline, ahead of the exception handler, so the
    /// status it logs is the one the caller actually received -- including the handler's 500 and
    /// 409, the size limit's 413 and the rate limiter's 429.
    /// </summary>
    public static IApplicationBuilder UseClimateProjectRequestLogging(this IApplicationBuilder app)
    {
        ArgumentNullException.ThrowIfNull(app);

        return app.Use(async (context, next) =>
        {
            context.Response.OnStarting(static state =>
            {
                var httpContext = (HttpContext)state;
                httpContext.Response.Headers[HeaderName] = httpContext.TraceIdentifier;
                return Task.CompletedTask;
            }, context);

            if (IsUnloggedPath(context.Request.Path))
            {
                await next(context);
                return;
            }

            // Read BEFORE the rest of the pipeline runs: the exception handler clears the
            // endpoint when it re-executes, so after a 500 GetEndpoint() is null and the line
            // would name "(unmatched)" for a request that did match.
            var route = RateLimitPolicies.RouteNameFor(context);
            var started = Stopwatch.GetTimestamp();
            var completed = false;

            try
            {
                await next(context);
                completed = true;
            }
            finally
            {
                // In case routing had not run yet when this middleware was entered.
                if (route == RateLimitPolicies.UnmatchedRouteName)
                {
                    route = RateLimitPolicies.RouteNameFor(context);
                }

                // An exception that escaped everything below is a 500 the server will write.
                var statusCode = !completed && !context.Response.HasStarted
                    ? StatusCodes.Status500InternalServerError
                    : context.Response.StatusCode;

                context.RequestServices
                    .GetRequiredService<ILoggerFactory>()
                    .CreateLogger(LogCategory)
                    .LogInformation(
                        LinePrefix + " {Method} {Route} {StatusCode} {ElapsedMs}ms id={RequestId}",
                        context.Request.Method,
                        route,
                        statusCode,
                        (long)Stopwatch.GetElapsedTime(started).TotalMilliseconds,
                        context.TraceIdentifier);
            }
        });
    }
}
