/**
 * Analítica, redesigned (canvas board "AnalyticsDashboard"): one job — which references
 * the company can be compared against, and how many AI findings wait for review. The
 * per-dimension comparison lives in Puntos de Referencia, and the header says so.
 *
 * Assembled from reads that exist: `GET /admin/benchmarks` (+ each row's detail for the
 * cohort size), `GET /admin/ai-insights` and `GET /surveys` for the wave the references
 * are read against. The previous `pages/AnalyticsDashboardPage.tsx` stays in the tree as
 * the wiring reference; the router no longer mounts it.
 *
 * Apple design (11 Nov): `PageHeader`, bordered cards with no shadow, the column heads in the
 * table primitive's sentence case, figures in the sans at tabular figures (no third face), and
 * neutral priority chips — green, amber and red belong to the three result areas only. No
 * "generated by AI" label on the findings: the server stores whatever text it is sent and
 * records no origin. Under md the Grupo and Calidad columns fold into the reference's line.
 */

const MAX_INSIGHTS_BESIDE = 3

export default function AnalyticsNextPage() {
  // The route's one role branch (#471): a super administrator reading one tenant's analytics gets
  // the per-role canvas's `./super/SuperAnalyticsView`, as the old AnalyticsDashboardPage dispatched
  // before this page replaced it on the route. Read off the claim, as that page does, so it renders
  // outside CompanyContextProvider. Every other role gets the company administrator's board.
  return readViewerClaims().role === 'super_admin' ? <SuperAnalyticsView /> : <AnalyticsNextPageForAdmins />
}

function AnalyticsNextPageForAdmins() {
  const { t } = useTranslation()
  const { companyId } = useParams<{ companyId: string }>()
  const companyName = useCompanyName()
  const { state, reload } = useAnalyticsModel(companyId)
  const company = companyName ?? t('insights.next.thisCompany')

  if (!companyId) return <p role="alert">{t('common.noCompanyAssociated')}</p>

  return (
    <div>
      <PageHeader
        // The header rule every admin screen follows (review 12 Nov): the eyebrow is the sidebar
        // section the page sits in, and a top-level page carries no breadcrumb. The company in
        // scope is named once, by the top bar, for every role.
        eyebrow={t('navigation.sectionAnalytics')}
        title={t('analytics.next.title')}
        description={t('analytics.next.description')}
        actions={
          <Button asChild variant="outline">
            <Link to="/analytics/benchmarks">
              <Gauge aria-hidden="true" />
              {t('navigation.references')}
            </Link>
          </Button>
        }
      />

      {state.status === 'loading' ? (
        <LoadingState rows={5} label={t('common.loading')} />
      ) : state.status === 'failed' ? (
        <ErrorState
          title={t('errors.generic')}
          description={state.message}
          action={
            <Button variant="outline" onClick={() => void reload()}>
              {t('common.retry')}
            </Button>
          }
        />
      ) : (
        // The board's two columns, 16px apart (AnalyticsDashboard.dc.html: `minmax(0, 1fr) 360px; gap: 16px`).
        <div data-testid="analytics-columns" className="grid items-start gap-4 xl:grid-cols-[minmax(0,1fr)_22.5rem]">
          <section aria-labelledby="analytics-references" className="min-w-0">
            <SectionHeading
              id="analytics-references"
              title={t('analytics.next.references')}
              count={state.data.benchmarks.length}
              aside={
                state.data.latestWave
                  ? t('analytics.next.againstWave', {
                      title: state.data.latestWave.title ?? t('surveys.untitled'),
                      count: state.data.latestWave.responseCount,
                    })
                  : null
              }
            />
            <div className={`${CARD} overflow-hidden`}>
              <Table>
                <TableHeader>
                  <TableRow className="hover:bg-transparent">
                    <TableHead scope="col">{t('analytics.next.colReference')}</TableHead>
                    <TableHead scope="col" className="w-40">{t('analytics.next.colScope')}</TableHead>
                    <TableHead scope="col" numeric className="hidden w-32 md:table-cell">{t('analytics.next.colGroup')}</TableHead>
                    <TableHead scope="col" numeric className="hidden w-32 md:table-cell">{t('analytics.next.colQuality')}</TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {state.data.benchmarks.map((row) => (
                    <BenchmarkTableRow key={row.id} row={row} />
                  ))}
                </TableBody>
              </Table>
              {!state.data.benchmarks.some((row) => !row.isGlobal) && (
                <EmptyRow
                  // The board's row: the ground tint (#f8f7fb) under a white tile, 14px 12px 16px.
                  className="gap-3 border-t border-line-light bg-surface-outer px-3 pb-4 pt-3.5"
                  iconTone="card"
                  icon={<Gauge />}
                  title={t('analytics.next.noOwnTitle', { company })}
                  lines={[t('analytics.next.noOwnBody')]}
                />
              )}
            </div>
          </section>

          <section aria-labelledby="analytics-insights" className="min-w-0">
            <SectionHeading
              id="analytics-insights"
              title={t('analytics.next.insights')}
              count={openInsightCount(state.data.insights)}
              aside={t('analytics.next.toReview')}
            />
            <div className={`${CARD} overflow-hidden`}>
              {openInsightCount(state.data.insights) === 0 ? (
                <div className="flex items-start gap-3.5 p-4.5">
                  <IconBox>
                    <Sparkles />
                  </IconBox>
                  <div className="flex min-w-0 flex-col items-start gap-1.5 text-sm">
                    <p className="m-0 text-base font-semibold text-fg-primary">{t('insights.next.emptyTitle')}</p>
                    <p className="m-0 leading-normal text-fg-secondary">
                      {state.data.insights.length === 0
                        ? t('analytics.next.insightsEmpty')
                        : t('analytics.next.insightsAllReviewed')}
                    </p>
                    <Link to="/analytics/ai-insights" className="inline-flex min-h-11 items-center gap-1 text-accent-blue-ink pointer-fine:min-h-0">
                      {t('analytics.next.openInsights')}
                      <ArrowRight aria-hidden="true" className="size-3.5" />
                    </Link>
                  </div>
                </div>
              ) : (
                <ul className="m-0 list-none divide-y divide-line-light p-0">
                  {state.data.insights
                    .filter((insight) => !insight.isAcknowledged)
                    .slice(0, MAX_INSIGHTS_BESIDE)
                    .map((insight) => (
                      <li key={insight.id} data-testid="analytics-insight" className="flex items-start gap-2.5 px-4 py-3 text-base">
                        <Chip tone="neutral" label={insightPriorityLabel(t, insight.priority)} className="mt-px shrink-0" />
                        <span className="min-w-0 text-fg-primary">{insight.title}</span>
                      </li>
                    ))}
                  <li className="px-4 py-1.5 text-sm">
                    <Link to="/analytics/ai-insights" className="inline-flex min-h-11 items-center gap-1 text-accent-blue-ink pointer-fine:min-h-8">
                      {t('analytics.next.openInsights')}
                      <ArrowRight aria-hidden="true" className="size-3.5" />
                    </Link>
                  </li>
                </ul>
              )}
            </div>
          </section>
        </div>
      )}
    </div>
  )
}

function typeLabel(t: (key: string) => string, type: string): string {
  const known = ['industry', 'internal', 'regional', 'company_size']
  return known.includes(type) ? t(`analytics.next.type.${type}`) : type
}

function categoryLabel(t: (key: string) => string, category: string): string {
  return ['climate', 'engagement'].includes(category) ? t(`analytics.next.category.${category}`) : category
}

function BenchmarkTableRow({ row }: { row: BenchmarkRow }) {
  const { t, locale } = useTranslation()
  const facts = [
    typeLabel(t, row.type),
    categoryLabel(t, row.category),
    row.isActive ? t('analytics.next.active') : t('analytics.next.inactive'),
    ...(row.isActive ? [t('analytics.next.usedByBenchmarks')] : []),
  ]
  return (
    <TableRow data-testid="benchmark-row" className="border-line-light">
      <TableCell className="py-3 align-top">
        <div className="font-semibold text-fg-primary">{row.name}</div>
        <div className="text-sm text-fg-tertiary">{facts.join(' · ')}</div>
        {/* Under md the Grupo and Calidad columns fold into this line, so a phone reads the
            quality without a sideways scroll nothing shows it has (HIG layout.md). The group
            is left out when it cannot be read — never printed as 0. */}
        <div data-slot="reference-folded" className="text-sm tabular-nums text-fg-tertiary md:hidden">
          {[
            row.groupSize === null ? null : t('analytics.next.groupFact', { count: row.groupSize.toLocaleString(locale) }),
            t('analytics.next.qualityFact', {
              value: row.qualityScore === null ? t('analytics.next.qualityPending') : formatMetric(row.qualityScore, QUALITY_SCORE_FORMAT, locale),
            }),
          ]
            .filter((part): part is string => part !== null)
            .join(' · ')}
        </div>
      </TableCell>
      <TableCell className="py-3">
        <Chip
          tone="neutral"
          label={row.isGlobal ? t('analytics.next.scopeGlobal') : t('analytics.next.scopeOwn')}
        />
      </TableCell>
      <TableCell numeric className="hidden py-3 text-sm text-fg-tertiary md:table-cell">
        {row.groupSize === null ? (
          '—'
        ) : (
          <>
            <span className="text-base text-fg-primary">{row.groupSize.toLocaleString(locale)}</span>{' '}
            {t('analytics.next.companies')}
          </>
        )}
      </TableCell>
      <TableCell numeric className="hidden py-3 text-sm text-fg-tertiary md:table-cell">
        {row.qualityScore === null ? (
          t('analytics.next.qualityPending')
        ) : (
          <span className="text-base text-fg-primary">{formatMetric(row.qualityScore, QUALITY_SCORE_FORMAT, locale)}</span>
        )}
      </TableCell>
    </TableRow>
  )
}
